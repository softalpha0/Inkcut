import fsp from "node:fs/promises";
import path from "node:path";
import { ensureFonts, writeFileAtomic } from "../util/fs.js";
import { runFfmpeg } from "../util/ffmpeg.js";
import { CAPTION_FONT_NAME, escapeAssText } from "./captions.js";

/** YouTube's recommended thumbnail size. */
export const THUMBNAIL_WIDTH = 1280;
export const THUMBNAIL_HEIGHT = 720;

export interface ThumbnailRenderJob {
  projectDir: string;
  /** Absolute path of the drawn picture (any size; cropped to 16:9). */
  imagePath: string;
  headline: string;
  /** Folder of .ttf files for libass. */
  fontsDir: string;
  /** Absolute paths of the two JPEGs to write. */
  outFile: string;
  cleanFile: string;
}

const WHITE = "&H00FFFFFF";
/** Colour overrides (\c&HBBGGRR&): white, and Inkcut marker yellow #FFD43B. */
const WHITE_TAG = "&HFFFFFF&";
const YELLOW_TAG = "&H3BD4FF&";

/**
 * Headline as ASS text: upper case, the *starred* word in yellow (the last word
 * when nothing is starred), wrapped on word boundaries by libass.
 */
export function headlineAssText(headline: string): string {
  const upper = escapeAssText(headline.trim().toUpperCase());
  const parts = upper.split(/(\*[^*]+\*)/).filter(Boolean);
  const starred = parts.some((p) => /^\*[^*]+\*$/.test(p));
  if (starred) {
    return parts
      .map((p) => (/^\*[^*]+\*$/.test(p) ? `{\\c${YELLOW_TAG}}${p.slice(1, -1)}{\\c${WHITE_TAG}}` : p))
      .join("")
      .replace(/\*/g, "")
      .replace(/\s+/g, " ")
      .trim();
  }
  const words = upper.replace(/\*/g, "").split(/\s+/).filter(Boolean);
  if (words.length < 2) return `{\\c${YELLOW_TAG}}${words.join(" ")}`;
  const last = words.pop()!;
  return `${words.join(" ")} {\\c${YELLOW_TAG}}${last}`;
}

/** Big outlined headline on the left half of a 1280x720 frame. */
export function buildThumbnailAss(headline: string): string {
  const words = headline.replace(/\*/g, " ").split(/\s+/).filter(Boolean).length;
  // As big as fits the left half: thumbnails are mostly seen at phone size.
  const fontSize = words <= 1 ? 210 : words === 2 ? 180 : words === 3 ? 150 : 128;
  return [
    "[Script Info]",
    "; Generated by Inkcut",
    "ScriptType: v4.00+",
    `PlayResX: ${THUMBNAIL_WIDTH}`,
    `PlayResY: ${THUMBNAIL_HEIGHT}`,
    "WrapStyle: 0",
    "ScaledBorderAndShadow: yes",
    "",
    "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
    // Alignment 4 = middle left; MarginR keeps the text in the left half, away from the character.
    `Style: Headline,${CAPTION_FONT_NAME},${fontSize},${WHITE},${WHITE},&H00000000,&H96000000,0,0,0,0,100,100,1,0,1,12,7,4,52,560,40,1`,
    "",
    "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    `Dialogue: 0,0:00:00.00,0:00:10.00,Headline,,0,0,0,,${headlineAssText(headline)}`,
    "",
  ].join("\n");
}

function rel(from: string, to: string): string {
  return path.relative(from, to).split(path.sep).join("/");
}

/**
 * Spec §5.5: crop the picture to 1280x720 with a little extra colour pop, then
 * burn in the headline. Writes the text version and a clean version.
 */
export async function renderThumbnail(job: ThumbnailRenderJob): Promise<void> {
  const renderDir = path.join(job.projectDir, "render");
  const fontsLocal = path.join(renderDir, "fonts");
  await ensureFonts(job.fontsDir, fontsLocal);
  await fsp.mkdir(path.dirname(job.outFile), { recursive: true });

  const base =
    `scale=${THUMBNAIL_WIDTH}:${THUMBNAIL_HEIGHT}:force_original_aspect_ratio=increase,` +
    `crop=${THUMBNAIL_WIDTH}:${THUMBNAIL_HEIGHT},eq=saturation=1.2:contrast=1.06`;
  // Working files go in render/, which is never uploaded with the project's assets.
  const assFile = path.join(renderDir, path.basename(job.outFile).replace(/\.jpg$/, ".ass"));
  await writeFileAtomic(assFile, buildThumbnailAss(job.headline));

  const render = async (vf: string, out: string) => {
    const tmp = out.replace(/\.jpg$/, ".tmp.jpg");
    await runFfmpeg(
      [
        "-i",
        rel(job.projectDir, job.imagePath),
        "-vf",
        vf,
        "-frames:v",
        "1",
        // JPEG quality 2-3 keeps a 1280x720 frame well under YouTube's 2 MB limit.
        "-q:v",
        "3",
        rel(job.projectDir, tmp),
      ],
      { cwd: job.projectDir },
    );
    await fsp.rename(tmp, out);
  };
  await render(base, job.cleanFile);
  // Relative paths keep Windows drive letters ("C:") out of the filter string.
  await render(
    `${base},subtitles=${rel(job.projectDir, assFile)}:fontsdir=${rel(job.projectDir, fontsLocal)}`,
    job.outFile,
  );
  await fsp.rm(assFile, { force: true });
}
